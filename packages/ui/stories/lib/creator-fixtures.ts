const toHandle = (name: string) => `@${name.toLowerCase().replace(/[^a-z]+/g, "")}`;

const toEmail = (name: string) =>
  `${name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[^a-z ]/g, "")
    .replace(" ", ".")}@gmail.com`;

export const CREATORS: Creator[] = CREATOR_ROWS.map(
  (
    [
      name,
      avatarSeed,
      platform,
      followers,
      engagementRate,
      averageViews,
      status,
      tags,
      location,
      lastActivity,
    ],
    index,
  ) => ({
    id: `creator-${index + 1}`,
    name,
    email: toEmail(name),
    imageUrl: avatarSeed === null ? null : avatarUrl(avatarSeed),
    platform,
    handle: toHandle(name),
    followers,
    engagementRate,
    averageViews,
    rateUsd: Math.round(followers / 1_000) * 12 + 150,
    collaborations: (index * 7) % 13,
    status,
    tags,
    location,
    lastActivity,
  }),
);
